-- Accounting controls: chart of accounts, fiscal years and periods.
CREATE TABLE IF NOT EXISTS fiscal_years (
    fiscal_year_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    fiscal_year integer NOT NULL,
    database_name varchar(250) NOT NULL DEFAULT '',
    start_date date NOT NULL,
    end_date date NOT NULL,
    is_current boolean NOT NULL DEFAULT false,
    is_closed boolean NOT NULL DEFAULT false,
    closed_by varchar(100),
    closed_at timestamptz,
    UNIQUE(company_id, fiscal_year),
    CHECK (start_date <= end_date)
);
CREATE TABLE IF NOT EXISTS chart_of_accounts (
    account_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    account_code varchar(100) NOT NULL,
    account_name varchar(250) NOT NULL CHECK (btrim(account_name) <> ''),
    account_type varchar(20) NOT NULL CHECK (account_type IN ('ASSET','LIABILITY','EQUITY','REVENUE','EXPENSE')),
    parent_account_id uuid REFERENCES chart_of_accounts(account_id),
    is_postable boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(company_id, account_code)
);
CREATE INDEX IF NOT EXISTS ix_chart_of_accounts_parent ON chart_of_accounts(company_id, parent_account_id);
CREATE INDEX IF NOT EXISTS ix_chart_of_accounts_active ON chart_of_accounts(company_id, is_active, is_postable);
CREATE TABLE IF NOT EXISTS fiscal_periods (
    fiscal_period_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    fiscal_year_id bigint NOT NULL REFERENCES fiscal_years(fiscal_year_id),
    period_number integer NOT NULL CHECK (period_number BETWEEN 1 AND 13),
    period_name varchar(100) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED','LOCKED')),
    closed_by varchar(100),
    closed_at timestamptz,
    UNIQUE(company_id, fiscal_year_id, period_number),
    CHECK (start_date <= end_date)
);
CREATE INDEX IF NOT EXISTS ix_fiscal_periods_dates ON fiscal_periods(company_id, start_date, end_date, status);
ALTER TABLE journal_entries ADD COLUMN IF NOT EXISTS fiscal_period_id uuid NULL;
CREATE INDEX IF NOT EXISTS ix_journal_entries_period_status ON journal_entries(company_id, fiscal_period_id, status);

-- Create fiscal-year records for legacy journal years, preserving existing entries.
INSERT INTO fiscal_years(company_id, fiscal_year, database_name, start_date, end_date, is_current, is_closed)
SELECT DISTINCT company_id, EXTRACT(YEAR FROM entry_date)::integer, '', make_date(EXTRACT(YEAR FROM entry_date)::integer,1,1), make_date(EXTRACT(YEAR FROM entry_date)::integer,12,31), false, false
FROM journal_entries
ON CONFLICT(company_id, fiscal_year) DO NOTHING;

-- Generate 12 monthly periods for years that have no periods yet.
INSERT INTO fiscal_periods(fiscal_period_id, company_id, fiscal_year_id, period_number, period_name, start_date, end_date, status)
SELECT md5(fy.company_id::text || ':' || fy.fiscal_year::text || ':' || m.month_no::text)::uuid, fy.company_id, fy.fiscal_year_id, m.month_no,
       to_char(make_date(fy.fiscal_year,m.month_no,1),'YYYY-MM'),
       make_date(fy.fiscal_year,m.month_no,1),
       (make_date(fy.fiscal_year,m.month_no,1) + interval '1 month - 1 day')::date, 'OPEN'
FROM fiscal_years fy
CROSS JOIN generate_series(1,12) AS m(month_no)
WHERE NOT EXISTS (SELECT 1 FROM fiscal_periods fp WHERE fp.company_id=fy.company_id AND fp.fiscal_year_id=fy.fiscal_year_id);

-- Attach legacy journal rows to generated periods without deleting business data.
UPDATE journal_entries e SET fiscal_period_id = (
  SELECT fp.fiscal_period_id FROM fiscal_periods fp
  WHERE fp.company_id=e.company_id AND e.entry_date BETWEEN fp.start_date AND fp.end_date
  ORDER BY fp.start_date LIMIT 1
) WHERE e.fiscal_period_id IS NULL;

CREATE OR REPLACE FUNCTION shouttech_validate_journal_post() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.status = 1 THEN
    RAISE EXCEPTION 'Journal entries must be inserted as drafts and posted after lines are added';
  END IF;
  IF NEW.status = 1 AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status) THEN
    IF NEW.fiscal_period_id IS NULL THEN RAISE EXCEPTION 'Journal entry must belong to a fiscal period before posting'; END IF;
    IF NOT EXISTS (
      SELECT 1 FROM fiscal_periods fp JOIN fiscal_years fy ON fy.fiscal_year_id=fp.fiscal_year_id
      WHERE fp.fiscal_period_id=NEW.fiscal_period_id AND fp.company_id=NEW.company_id
        AND NEW.entry_date BETWEEN fp.start_date AND fp.end_date AND fp.status='OPEN' AND NOT fy.is_closed
    ) THEN RAISE EXCEPTION 'Fiscal period is closed or does not match journal date'; END IF;
    IF EXISTS (
      SELECT 1 FROM journal_entry_lines l LEFT JOIN chart_of_accounts a ON a.account_id=l.account_id AND a.company_id=NEW.company_id
      WHERE l.journal_entry_id=NEW.journal_entry_id AND (a.account_id IS NULL OR NOT a.is_active OR a.is_deleted OR NOT a.is_postable)
    ) THEN RAISE EXCEPTION 'Journal contains an inactive, missing, or non-postable account'; END IF;
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_journal_post_requires_open_period ON journal_entries;
CREATE TRIGGER trg_journal_post_requires_open_period BEFORE UPDATE OF status ON journal_entries
FOR EACH ROW EXECUTE FUNCTION shouttech_validate_journal_post();

DROP TRIGGER IF EXISTS trg_journal_post_insert_requires_open_period ON journal_entries;
CREATE TRIGGER trg_journal_post_insert_requires_open_period BEFORE INSERT ON journal_entries
FOR EACH ROW EXECUTE FUNCTION shouttech_validate_journal_post();

CREATE OR REPLACE FUNCTION shouttech_prevent_period_reopen() RETURNS trigger AS $$
BEGIN
  IF OLD.status='LOCKED' AND NEW.status <> 'LOCKED' THEN
    RAISE EXCEPTION 'Locked fiscal periods cannot be reopened';
  END IF;
  IF OLD.status='CLOSED' AND NEW.status='OPEN' THEN
    RAISE EXCEPTION 'Closed fiscal periods cannot be reopened through direct database updates';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_prevent_period_reopen ON fiscal_periods;
CREATE TRIGGER trg_prevent_period_reopen BEFORE UPDATE OF status ON fiscal_periods
FOR EACH ROW EXECUTE FUNCTION shouttech_prevent_period_reopen();

CREATE OR REPLACE FUNCTION shouttech_prevent_year_reopen() RETURNS trigger AS $$
BEGIN
  IF OLD.is_closed=true AND NEW.is_closed=false THEN
    RAISE EXCEPTION 'Closed fiscal years cannot be reopened through direct database updates';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_prevent_year_reopen ON fiscal_years;
CREATE TRIGGER trg_prevent_year_reopen BEFORE UPDATE OF is_closed ON fiscal_years
FOR EACH ROW EXECUTE FUNCTION shouttech_prevent_year_reopen();
