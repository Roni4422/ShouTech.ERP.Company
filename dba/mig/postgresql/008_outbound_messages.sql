CREATE TABLE IF NOT EXISTS outbound_messages (
    outbound_message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid,
    channel varchar(20) NOT NULL CHECK (channel IN ('WEBHOOK', 'EMAIL', 'SMS')),
    recipient_address text NOT NULL,
    subject varchar(500),
    body text NOT NULL,
    body_format varchar(20) NOT NULL DEFAULT 'TEXT',
    status varchar(20) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED', 'SENDING', 'SENT', 'FAILED')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    max_attempts integer NOT NULL DEFAULT 6 CHECK (max_attempts > 0),
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    last_error varchar(1000),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    sent_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_outbound_messages_due
    ON outbound_messages(status, next_attempt_at, outbound_message_id);
